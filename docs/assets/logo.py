# Generates the Lituus logo, Dwindle: a golden rectangle cut into window tiles, as Hyprland's
# dwindle layout cuts the screen, with the spiral (a lituus) running through them.
#
#   python3 docs/assets/logo.py
#
# writes, from the repository root:
#   packaging/linux/icons/ch.giosuel.Lituus.svg   the app icon, full colour on a tile
#   crates/app/ui/assets/logo-mark.svg            the window icon (the same)
#   website/public/favicon.svg, website/src/assets/mark.svg   the website's (the same)
#   crates/app/src/tray-logo.svg                  the tray icon: one colour, the spiral cut out
#   crates/app/ui/logo.slint                      the sidebar's: drawn in the theme's colours
import os

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..")
PHI = (1 + 5 ** 0.5) / 2


def split(w, n):
    """The tiles (x, y, w, h) and the spiral's quarter arcs ((x0, y0), (x1, y1)) for a golden
    rectangle w wide, centred in 128x128: squares cut off left, top, right, bottom, in turn."""
    h = w / PHI
    x, y = (128 - w) / 2, (128 - h) / 2
    tiles, arcs = [], []
    for i in range(n):
        side = i % 4
        if side == 0:
            a = h
            tiles.append((x, y, a, h)); arcs.append(((x, y + h), (x + a, y))); x, w = x + a, w - a
        elif side == 1:
            a = w
            tiles.append((x, y, w, a)); arcs.append(((x, y), (x + w, y + a))); y, h = y + a, h - a
        elif side == 2:
            a = h
            tiles.append((x + w - a, y, a, h)); arcs.append(((x + w, y), (x + w - a, y + h))); w = w - a
        else:
            a = w
            tiles.append((x, y + h - a, w, a)); arcs.append(((x + w, y + h), (x, y + h - a))); h = h - a
    return tiles, arcs


def spiral(arcs, sep=" "):
    d = f"M{sep}{arcs[0][0][0]:.2f} {arcs[0][0][1]:.2f}"
    for (sx, sy), (ex, ey) in arcs:
        d += f" A{sep}{abs(ex - sx):.2f} {abs(ey - sy):.2f} 0 0 1 {ex:.2f} {ey:.2f}"
    return d


def radius(w, h, most):
    return min(most, w / 4, h / 4)


def svg(body):
    return f'<svg xmlns="http://www.w3.org/2000/svg" width="128" height="128" viewBox="0 0 128 128">{body}</svg>\n'


def icon():
    """Full colour, on a dark tile: seven tiles from dim to the teal accent, a light spiral."""
    g = 2.5
    tiles, arcs = split(108, 7)
    shades = ["#24312e", "#29403a", "#2f4f47", "#376055", "#417466", "#4f9c89", "#5cc8b0"]
    body = '<rect x="4" y="4" width="120" height="120" rx="28" fill="#14171a" stroke="#262b30" stroke-width="2"/>'
    for (x, y, w, h), c in zip(tiles, shades):
        body += f'<rect x="{x + g:.2f}" y="{y + g:.2f}" width="{w - 2 * g:.2f}" height="{h - 2 * g:.2f}" rx="{radius(w, h, 6):.2f}" fill="{c}"/>'
    body += f'<path d="{spiral(arcs)}" fill="none" stroke="#e9efe9" stroke-width="3.5" stroke-linecap="round"/>'
    return svg(body)


# The small mark (sidebar and tray): no tile, five bigger tiles, a heavier spiral.
MARK_W, MARK_N, MARK_GAP, MARK_LINE = 114, 5, 5, 6


def tray():
    """One colour: the tiles in the accent, the spiral cut out of them. One tile fewer than the
    sidebar's, since bars draw it at 22 px."""
    tiles, arcs = split(MARK_W, MARK_N - 1)
    g = MARK_GAP / 2
    body = ('<mask id="m"><rect width="128" height="128" fill="#fff"/>'
            f'<path d="{spiral(arcs)}" fill="none" stroke="#000" stroke-width="{MARK_LINE + 1}" stroke-linecap="round"/></mask>'
            '<g mask="url(#m)" fill="#5cc8b0">')
    for x, y, w, h in tiles:
        body += f'<rect x="{x + g:.2f}" y="{y + g:.2f}" width="{w - 2 * g:.2f}" height="{h - 2 * g:.2f}" rx="{radius(w, h, 9):.2f}"/>'
    return svg(body + "</g>")


def slint():
    """The sidebar's mark in the theme's colours: the biggest tile dimmest, the smallest the accent,
    the spiral in the text colour."""
    tiles, arcs = split(MARK_W, MARK_N)
    g = MARK_GAP / 2
    out = [
        "// Generated by docs/assets/logo.py: the Dwindle mark, in the theme's colours.",
        'import { Theme } from "theme.slint";',
        "",
        "export component Logo inherits Rectangle {",
        "    in property <length> size: 28px;",
        "    width: size;",
        "    height: size;",
    ]
    for i, (x, y, w, h) in enumerate(tiles):
        f = i / (len(tiles) - 1)
        out.append(
            f"    Rectangle {{ x: {(x + g) / 128:.4f} * root.width; y: {(y + g) / 128:.4f} * root.height; "
            f"width: {(w - 2 * g) / 128:.4f} * root.width; height: {(h - 2 * g) / 128:.4f} * root.height; "
            f"border-radius: {radius(w, h, 9) / 128:.4f} * root.width; background: Theme.accent.mix(Theme.accent-soft-border, {f:.2f}); }}")
    out.append(
        "    Path {\n        width: 100%; height: 100%;\n        viewbox-width: 128; viewbox-height: 128;\n"
        f"        stroke: Theme.text; stroke-width: root.width * {MARK_LINE} / 128; fill: transparent; stroke-line-cap: round;\n"
        f'        commands: "{spiral(arcs)}";\n    }}')
    out.append("}")
    return "\n".join(out) + "\n"


def write(path, text):
    with open(os.path.join(ROOT, path), "w") as f:
        f.write(text)


if __name__ == "__main__":
    for path in ("packaging/linux/icons/ch.giosuel.Lituus.svg", "crates/app/ui/assets/logo-mark.svg",
                 "website/public/favicon.svg", "website/src/assets/mark.svg"):
        write(path, icon())
    write("crates/app/src/tray-logo.svg", tray())
    write("crates/app/ui/logo.slint", slint())
